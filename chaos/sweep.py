"""Fault-rate sweep: how each config degrades as the network gets worse.

    python -m chaos.sweep --scenarios 100 --seed 0

Each level sets the total fault probability per request, split evenly across
429 / 5xx-before-commit / commit-then-504 / delayed delivery. Crash schedules
and planner temperatures come from the same seeded scenarios as results.md.
Writes results/sweep.md; never edit it by hand.
"""

from __future__ import annotations

import argparse
import os
import time
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
from dataclasses import replace
from pathlib import Path
from statistics import mean

from agents.campaign import campaign_tools
from chaos.bench import RESULTS, VARIANTS, _git_sha, _table, update_readme
from chaos.driver import RunReport, Scenario, run_scenario
from chaos.scenarios import generate
from harness.journal import DURABILITY

LEVELS = (0.0, 0.1, 0.2, 0.4, 0.6, 0.8)
CONFIGS = ["naive_retry", "keys_only", "harness", "harness_cas"]


def at_level(scenario: Scenario, level: float) -> Scenario:
    p = round(level / 4, 4)
    faults = replace(scenario.faults, p_429=p, p_5xx=p, p_lost_ack=p, p_delayed=p)
    return replace(scenario, faults=faults)


def _run(task: tuple[Scenario, str, float, str]) -> tuple[float, RunReport]:
    scenario, name, level, durability = task
    config, conditional = VARIANTS[name]
    return level, run_scenario(at_level(scenario, level), config, tools=campaign_tools(conditional),
                               durability=durability)


def render(runs: dict[tuple[str, float], list[RunReport]], n: int, args) -> str:
    def grid(cell) -> str:
        return _table(["config", *(f"{level:.0%} faults" for level in LEVELS)],
                      [[f"`{name}`", *(cell(runs[(name, level)]) for level in LEVELS)] for name in CONFIGS])

    return "\n".join([
        "# Fault-rate sweep",
        "",
        f"Generated by `python -m chaos.sweep --scenarios {n} --seed {args.seed}` at commit "
        f"`{_git_sha()}`. Do not edit by hand.",
        "",
        f"{n} seeded scenarios per cell (the first {n} of results.md, same crash schedules and "
        "temperatures). Each column sets the total probability that a request draws a fault, "
        "split evenly across 429, 5xx-before-commit, commit-then-504 and delayed delivery.",
        "",
        "Duplicate effects (runs with any duplicate in brackets):",
        "",
        grid(lambda rs: f"{sum(r.check.duplicate_total for r in rs)} "
                        f"({sum(1 for r in rs if r.check.duplicate_total)})"),
        "",
        "Runs that finished (the rest hit the 12-incarnation limit or gave up):",
        "",
        grid(lambda rs: f"{100 * sum(r.finished for r in rs) / len(rs):.0f}%"),
        "",
        "Escalations to a human, per run:",
        "",
        grid(lambda rs: f"{mean(r.escalations for r in rs):.2f}"),
        "",
        "Planner calls per run (9 for a clean run):",
        "",
        grid(lambda rs: f"{mean(r.planner_calls for r in rs):.1f}"),
        "",
        "Above 9 for the harness: a read that kept failing (metrics, or the conditional write's "
        "precondition read) is reported to the planner, which plans that step again. Nothing had "
        "been sent for it. The baselines re-plan from the goal after every crash.",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--scenarios", type=int, default=100)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--durability", choices=sorted(DURABILITY), default="send")
    parser.add_argument("--workers", type=int, default=os.cpu_count() or 1)
    parser.add_argument("--out", type=Path, default=RESULTS)
    args = parser.parse_args()

    scenarios = generate(args.scenarios, args.seed)
    tasks = [(s, name, level, args.durability) for level in LEVELS for name in CONFIGS for s in scenarios]
    started = time.perf_counter()
    with ProcessPoolExecutor(max_workers=args.workers) as pool:
        results = list(pool.map(_run, tasks, chunksize=8))
    runs: dict[tuple[str, float], list[RunReport]] = defaultdict(list)
    for level, report in results:
        runs[(report.config, level)].append(report)

    args.out.mkdir(parents=True, exist_ok=True)
    text = render(runs, len(scenarios), args)
    (args.out / "sweep.md").write_text(text, encoding="utf-8", newline="\n")
    if args.out.resolve() == RESULTS:
        update_readme("sweep", text.split("\n", 2)[2].strip())
    print(f"{len(results)} runs in {time.perf_counter() - started:.0f}s -> {args.out / 'sweep.md'}")


if __name__ == "__main__":
    main()
